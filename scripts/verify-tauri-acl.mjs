#!/usr/bin/env node
/**
 * verify:tauri-acl — every Tauri command the portal invokes must be PERMITTED by the
 * capability set, for the origin the window actually loads.
 *
 * WHY THIS GATE EXISTS (D-022, and D-010 before it)
 * -------------------------------------------------
 * The main window loads a REMOTE origin — `WebviewUrl::External("http://127.0.0.1:8787")`
 * (src-tauri/src/main.rs) — and Tauri v2 refuses EVERY command from a non-local origin
 * unless a capability explicitly grants it. From tauri-2.11.2,
 * `crates/tauri/src/webview/mod.rs`:
 *
 *     // Check ACL on plugin commands, when the app defined its ACL manifest,
 *     // or when the request comes from a non-local (remote) origin.
 *     if (plugin_command.is_some() || has_app_acl_manifest || !is_local) … && invoke.acl.is_none() {
 *         invoke.resolver.reject(format!("Command {} not allowed by ACL", request.cmd));
 *
 * Registering a command in `generate_handler!` therefore does NOT make it callable. Three
 * files must agree — and nothing in the build tells you when they don't:
 *
 *     1. src-tauri/src/main.rs      `generate_handler![…]`   the command exists
 *     2. src-tauri/build.rs         `AppManifest::commands`  an `allow-<kebab>` permission
 *                                                            is autogenerated for it
 *     3. src-tauri/capabilities/*   `permissions: […]`       that permission is granted
 *                                                            to window "main" + the remote origin
 *
 * D-010 was step 3 missing for the opener plugin (sign-in never opened a browser). D-022 was
 * steps 2+3 missing for all five app commands: "Check for updates" was ACL-rejected before
 * `check_for_update` ever ran, and so were the update banner (`get_available_update`), the
 * banner's install button (`install_update`), the runtime version (`app_version`) and the
 * post-destroy relaunch (`destroy_and_relaunch`). Every one of them fails SILENTLY — each
 * call site swallows the rejection — which is why the class survived two releases.
 *
 * THE CHECK IS DERIVED, NOT A LIST (meta-defect M-002: hand-maintained enumerations rot)
 * -------------------------------------------------------------------------------------
 * Nothing here enumerates the commands. The needed set is computed as
 * `registered ∩ invoked-by-the-frontend`, and compared BOTH ways against what the capability
 * grants: a new command wired into the UI without a grant REDs (A3), and a grant left behind
 * for a command the UI no longer calls REDs too (A4, least privilege). Add a sixth command
 * tomorrow and this gate already covers it.
 *
 * LIMITATIONS — what a GREEN verdict does NOT claim (stated because a gate that claims more
 * than it checks is exactly meta-defect M-001):
 *
 *   • **Permission SETS are opaque.** `core:default` is a bundle; this gate checks identifiers,
 *     not what a set expands to. It is a registered exception (see PERMISSION_EXCEPTIONS),
 *     pre-existing and accepted per the app-sandbox-hardening design. If you
 *     need the contents audited, that is a different gate.
 *   • **"Invoked" is a static approximation.** A command name assembled at runtime
 *     (`invoke(\`plugin:\${p}|x\`)`) is invisible here, and conversely a command name that happens
 *     to be the first string argument of some UNRELATED call would be read as invoked. Both are
 *     narrow: the first would RED at runtime instead (fail-safe), the second could let one stale
 *     grant look justified. Keep command names distinctive.
 *   • **It does not prove the app builds or runs.** No cargo here. Note that tauri-build ALSO
 *     fails the build when a capability names a permission the app manifest does not define
 *     (tauri-build/src/acl.rs validate_capabilities → `anyhow::bail!`), so this gate is the
 *     earlier, cheaper of two independent layers — not the only one.
 *   • **It does not prove the updater works.** Only a packaged, signed macOS build can prove
 *     download→verify→swap→relaunch. This gate proves the IPC is no longer refused before the
 *     command body runs.
 */
// MUTATION-TESTED: removed "allow-check-for-update" from capabilities/default.json (the exact
//   D-022 defect) → A3 REDs naming check_for_update; restored → GREEN.
// MUTATION-TESTED: reverted build.rs to a bare `tauri_build::build()` (no app manifest, so no
//   allow-* permission can exist) → A2 REDs on all five commands; restored → GREEN.
// MUTATION-TESTED: deleted app_version's only call site (VersionSection.svelte
//   `const v = await invoke('app_version')`), leaving its grant behind → A4 REDs on the now
//   stale over-grant ("unprefixed allow-app-version is not allow-<an invoked app command>");
//   restored → GREEN.
// MUTATION-TESTED: replaced the opener grant with "opener:default" → A6 REDs on
//   plugin:opener|open_url (and A4 on the unbacked set); restored → GREEN.
// MUTATION-TESTED: added "updater:default" to the capability → A7 AND A4 RED (Rust-driven
//   plugins must get no webview IPC); restored → GREEN.
// MUTATION-TESTED: pointed the capability's remote.urls at port 8788 → A8 REDs (a grant that
//   does not cover the loaded origin is not a grant); restored → GREEN.
//
// ── the three below close findings raised by an independent adversarial review ──
// MUTATION-TESTED (review finding 1 — A6 was silenceable by RENAMING): aliased the binding in
//   Header.svelte, `__TAURI_INTERNALS__?.invoke?.(…)` → `?.zz?.(…)`, AND deleted
//   "core:window:allow-start-dragging" — i.e. D-010 reintroduced. The pre-fix gate stayed GREEN
//   with A6 reporting "(none)" because plugin commands had only the `invoke(` derivation. With
//   the alias-resistant call-argument derivation the aliased call is still seen (A1b still
//   counts 4 plugin commands) and A6 REDs on the deleted grant; restored → GREEN.
// MUTATION-TESTED (review finding 2 — A4 only checked UNPREFIXED grants): added
//   "core:webview:allow-print" + "core:app:allow-set-app-theme", neither invoked. The pre-fix
//   gate stayed GREEN while its verdict claimed "no over-grant"; A4 now REDs on both, naming
//   the plugin command each would grant; restored → GREEN.
// MUTATION-TESTED (review finding 3): set the capability's "platforms" to ["linux"], which
//   makes tauri-build skip it on the shipped target so every grant is inert → A8 REDs;
//   restored → GREEN.
// MUTATION-TESTED: deleted permissions/autogenerated/check_for_update.toml → A5 REDs;
//   restored → GREEN.
// MUTATION-TESTED: dropped `app_version,` from the generate_handler! list while leaving its
//   #[tauri::command] and its call site → A1a AND A1c RED; restored → GREEN.
// MUTATION-TESTED: re-pointed check_for_update.toml's `commands.allow` at install_update
//   (identifier left intact, so A5 still passed) → A5b REDs; restored → GREEN.
// MUTATION-TESTED (anti-vacuity): replaced capabilities/default.json with unparseable JSON —
//   the gate FAILS CLOSED (A0 + A3 + A8 RED) rather than reading zero permissions as
//   "nothing to check"; restored → GREEN.
// All restored afterwards; the gate returns GREEN on the restored tree.
import './lib/gate-stdout.mjs'; // MUST be first: flushes VERDICT on a piped stdout
import { readFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve, extname } from 'node:path';
import { stripCommentsFor } from './lib/strip-comments.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => { try { return readFileSync(join(ROOT, p), 'utf8'); } catch { return ''; } };

let fail = 0;
const rec = (n, ok, d = '') => { console.log(`${ok ? 'PASS' : 'FAIL'}  ${n}${d ? ` — ${d}` : ''}`); if (!ok) fail = 1; };

const kebab = (c) => c.replace(/_/g, '-');           // tauri-utils acl/build.rs: allow-{command.replace('_',"-")}
const list = (s) => (s.size ? [...s].sort().join(', ') : '(none)');

// ── 1. REGISTERED — the commands main.rs actually exposes ────────────────────
// Extract the macro body first, THEN drop comments inside it. A whole-file `//` strip is
// unsafe on Rust (`"http://…"`, `'static` lifetimes, char literals); inside a
// `generate_handler![…]` body there are only identifiers, commas and comments, so a line
// strip there is lexically sound.
const mainrs = read('src-tauri/src/main.rs');
const handlerBody = (mainrs.match(/generate_handler!\s*\[([\s\S]*?)\]/) || [null, ''])[1];
const registered = new Set(
  handlerBody
    .replace(/\/\/[^\n]*/g, '')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split(/[,\s]+/)
    .map((t) => t.trim())
    .filter((t) => /^[a-z_][a-z0-9_]*$/.test(t)),
);
rec('A1. generate_handler! parsed and non-empty', registered.size > 0, list(registered));

// Cross-check the parse against the `#[tauri::command]` attributes themselves. If the macro
// body were ever written in a shape the extractor above mis-reads, `registered` would silently
// shrink and every downstream comparison would go quietly green on a smaller set — so compare
// it against an INDEPENDENT derivation. (It doubles as the "declared but never registered"
// check: such a command is dead code that no capability can reach.)
const declaredFns = new Set(
  [...mainrs.matchAll(/#\[tauri::command\][\s\S]{0,80}?\bfn\s+([a-z_][a-z0-9_]*)/g)].map((m) => m[1]),
);
const unregistered = [...declaredFns].filter((c) => !registered.has(c));
rec('A1a. every #[tauri::command] in main.rs is in generate_handler! (and the parse agrees)',
  declaredFns.size > 0 && unregistered.length === 0,
  unregistered.length ? `declared but not registered (or the handler parse missed it): ${unregistered.join(', ')}`
    : `${declaredFns.size} command attribute(s), all registered`);

// ── 2. INVOKED — what the portal calls over IPC ──────────────────────────────
// Two independent derivations, unioned, so neither can rot the contract alone:
//   (a) `invoke(…)` / `invoke?.(…)` call sites — catches plugin commands too;
//   (b) any REGISTERED command name appearing as a string literal in frontend code —
//       survives someone renaming the local `invoke` binding, which (a) would miss.
const FRONTEND_ROOT = 'portal-app/src';
const walk = (rel, out = []) => {
  const abs = join(ROOT, rel);
  if (!existsSync(abs)) return out;
  for (const e of readdirSync(abs)) {
    const child = `${rel}/${e}`;
    if (statSync(join(ROOT, child)).isDirectory()) walk(child, out);
    else if (['.svelte', '.ts', '.js', '.html'].includes(extname(e))) out.push(child);
  }
  return out;
};
const frontendFiles = walk(FRONTEND_ROOT);
// Comments stripped with THE ONE lexical scanner (scripts/lib/strip-comments.mjs, gated by
// verify:strip-comments) — a gate that reads prose as code is the M-001 failure, and this
// file's own doc comment quotes several command names.
const frontendCode = frontendFiles.map((f) => stripCommentsFor(f, read(f))).join('\n');

// (a) named `invoke(…)` call sites.
const invokedRaw = new Set(
  [...frontendCode.matchAll(/\binvoke\s*\??\s*\.?\s*\(\s*(['"`])([^'"`]+)\1/g)].map((m) => m[2]),
);
// (b) ALIAS-RESISTANT: a string literal in FIRST-ARGUMENT position of ANY call. The binding
// name is not part of the match, so renaming `invoke` — `__TAURI_INTERNALS__?.invoke?.('x')`
// → `?.zz?.('x')` — cannot hide the call. An adversarial review defeated the previous draft
// exactly there: aliasing the binding in Header.svelte AND deleting
// `core:window:allow-start-dragging` left the gate GREEN with A6 reporting "(none)" —
// D-010 reintroduced with zero signal, because plugin commands had only derivation (a).
// Requiring argument position (rather than "any string literal") also keeps an incidental
// object key or CSS class from being read as a call.
const callArgs = new Set(
  [...frontendCode.matchAll(/\(\s*(['"`])([^'"`\n]+)\1/g)].map((m) => m[2]),
);
const PLUGIN_CMD = /^plugin:[a-z0-9_-]+\|[a-z0-9_]+$/;
const invokedPlugin = new Set([...invokedRaw, ...callArgs].filter((c) => PLUGIN_CMD.test(c)));
const invokedApp = new Set([...invokedRaw].filter((c) => !c.startsWith('plugin:')));
for (const c of registered) if (callArgs.has(c)) invokedApp.add(c);
rec('A1b. frontend sources scanned', frontendFiles.length > 0,
  `${frontendFiles.length} file(s) · ${invokedApp.size} app command(s) · ${invokedPlugin.size} plugin command(s)`);

// The frontend may not invoke a command that does not exist — a rename would otherwise leave
// a dead call site that the ACL comparison below happily ignores.
const phantom = [...invokedApp].filter((c) => !registered.has(c));
rec('A1c. every app command the frontend invokes is registered in main.rs',
  phantom.length === 0, phantom.length ? `not in generate_handler!: ${phantom.join(', ')}` : 'no dead call sites');

const needed = new Set([...invokedApp].filter((c) => registered.has(c)));

// ── 3. DECLARED — build.rs must autogenerate a permission for each ───────────
// build.rs has no lifetimes/char literals, so a line-comment strip is safe here.
const buildrs = read('src-tauri/build.rs').replace(/\/\/[^\n]*/g, '');
const cmdsArg = (buildrs.match(/commands\s*\(\s*&\s*\[([\s\S]*?)\]/) || [null, ''])[1];
const declared = new Set([...cmdsArg.matchAll(/"([a-z0-9_]+)"/g)].map((m) => m[1]));
const undeclared = [...needed].filter((c) => !declared.has(c));
rec('A2. build.rs app manifest declares every invoked command (permissions can exist at all)',
  /app_manifest\s*\(/.test(buildrs) && undeclared.length === 0,
  undeclared.length
    ? `missing from AppManifest::commands: ${undeclared.join(', ')} — without this, no allow-* permission is generated and the capability grant would not even resolve`
    : `declared: ${list(declared)}`);

// ── 4. GRANTED — the capability set ──────────────────────────────────────────
const CAP_DIR = 'src-tauri/capabilities';
const capFiles = existsSync(join(ROOT, CAP_DIR))
  ? readdirSync(join(ROOT, CAP_DIR)).filter((f) => f.endsWith('.json')).map((f) => `${CAP_DIR}/${f}`)
  : [];
const caps = [];
for (const f of capFiles) {
  try { caps.push({ file: f, ...JSON.parse(read(f)) }); } catch { rec(`A0. ${f} parses as JSON`, false, 'invalid JSON'); }
}
const allPerms = caps.flatMap((c) => (Array.isArray(c.permissions) ? c.permissions : []).map((p) => (typeof p === 'string' ? p : p?.identifier)).filter(Boolean));
const appPerms = new Set(allPerms.filter((p) => !p.includes(':')));   // unprefixed ⇒ the app's own ACL manifest

const neededIds = new Set([...needed].map((c) => `allow-${kebab(c)}`));
const missing = [...needed].filter((c) => !appPerms.has(`allow-${kebab(c)}`));
rec('A3. every invoked app command is PERMITTED by a capability (the D-022 defect)',
  missing.length === 0,
  missing.length
    ? `ACL-rejected at runtime ("Command <cmd> not allowed by ACL"): ${missing.join(', ')} — add "allow-${kebab(missing[0])}" to ${CAP_DIR}/default.json`
    : `permitted: ${list(neededIds)}`);

// Least privilege, the other direction. An earlier draft only checked UNPREFIXED permissions,
// so an uninvoked `core:webview:allow-print` or `core:app:allow-set-app-theme` sailed through
// while the verdict still claimed "no over-grant" — a gate claiming more than it checks is
// M-001 with extra steps. So EVERY entry must now land in exactly one justified bucket:
//   1. unprefixed `allow-<cmd>`      where <cmd> is an invoked app command
//   2. `[core:]<plugin>:allow-<cmd>` where plugin:<plugin>|<cmd> is an invoked plugin command
//   3. a registered exception below, each carrying its reason
// Anything else REDs. The exception register is deliberately tiny and FAILS CLOSED: a new
// unjustified grant cannot be added without either an invoke to back it or a written reason
// here, where a reviewer sees it.
const PERMISSION_EXCEPTIONS = {
  'core:default': 'Tauri baseline core set (event/path/app-metadata + window getters). '
    + 'Pre-existing and accepted per the app-sandbox-hardening design. '
    + '⚠️ It is a permission SET — see the LIMITATIONS note in the header: this gate does NOT '
    + 'enumerate what a set contains, so what core:default grants is out of scope here.',
  'opener:allow-default-urls': 'Scope-only (D-010): supplies open_url\'s http/https/mailto/tel '
    + 'allowlist. Grants no command of its own, so no invoke can back it.',
};
const justify = (p) => {
  if (p in PERMISSION_EXCEPTIONS) return null;
  if (!p.includes(':')) {
    return neededIds.has(p) ? null : `unprefixed "${p}" is not allow-<an invoked app command>`;
  }
  const m = p.match(/^(?:core:)?([a-z0-9-]+):allow-([a-z0-9-]+)$/);
  if (!m) return `"${p}" is neither allow-<command> nor a registered exception`;
  const want = `plugin:${m[1]}|${m[2].replace(/-/g, '_')}`;
  return invokedPlugin.has(want) ? null : `"${p}" grants ${want}, which the frontend never invokes`;
};
const unjustified = allPerms.map((p) => justify(p)).filter(Boolean);
rec('A4. every granted permission is backed by an invoked command or a registered exception',
  unjustified.length === 0,
  unjustified.length ? unjustified.join('; ')
    : `${allPerms.length} grant(s): ${allPerms.length - Object.keys(PERMISSION_EXCEPTIONS).length} command-backed, `
      + `${Object.keys(PERMISSION_EXCEPTIONS).length} registered exception(s)`);
rec('A4b. no globbed permission identifier anywhere in the capability set',
  !allPerms.some((p) => p.includes('*')),
  allPerms.filter((p) => p.includes('*')).join(', ') || 'none');

// ── 5. The autogenerated permission files back the grants ────────────────────
// build.rs regenerates these; if one is absent the grant resolves only after a build that
// happens to run first, and a stale/edited file would silently change what is allowed.
const PERM_DIR = 'src-tauri/permissions/autogenerated';
const permIds = new Set();
if (existsSync(join(ROOT, PERM_DIR))) {
  for (const f of readdirSync(join(ROOT, PERM_DIR)).filter((f) => f.endsWith('.toml'))) {
    for (const m of read(`${PERM_DIR}/${f}`).matchAll(/identifier\s*=\s*"([^"]+)"/g)) permIds.add(m[1]);
  }
}
const unbacked = [...neededIds].filter((id) => !permIds.has(id));
rec('A5. each granted app permission exists in permissions/autogenerated/',
  unbacked.length === 0,
  unbacked.length ? `no autogenerated definition for: ${unbacked.join(', ')}` : `${permIds.size} identifier(s) defined`);

// The identifier existing is not the same as it allowing the command you think it allows.
// These files are marked DO NOT EDIT precisely because the binding — identifier ⇄
// `commands.allow` — is what the ACL resolves; re-pointing one by hand would silently widen
// or redirect a grant. Assert the binding, not the name.
const mispointed = [...needed].filter((c) => {
  const body = read(`${PERM_DIR}/${c}.toml`);
  return !new RegExp(`identifier\\s*=\\s*"allow-${kebab(c)}"[\\s\\S]{0,200}?commands\\.allow\\s*=\\s*\\["${c}"\\]`).test(body);
});
rec('A5b. each autogenerated permission still allows the command it is named for',
  mispointed.length === 0,
  mispointed.length ? `identifier ⇄ commands.allow binding is wrong or hand-edited: ${mispointed.join(', ')}` : 'bindings intact');

// ── 6. Plugin commands (the D-010 class) ─────────────────────────────────────
// `plugin:<p>|<cmd>` needs `<p>:allow-<kebab>` (or `core:<p>:allow-<kebab>` for a core
// plugin such as `window`). A `:default` permission set is deliberately NOT accepted: it is
// a bundle whose contents can change under us, and least privilege wants the command named.
const pluginMisses = [];
for (const c of invokedPlugin) {
  const m = c.match(/^plugin:([a-z0-9-]+)\|(.+)$/);
  if (!m) { pluginMisses.push(`${c} (unparseable)`); continue; }
  const [, plugin, command] = m;
  const want = [`${plugin}:allow-${kebab(command)}`, `core:${plugin}:allow-${kebab(command)}`];
  if (!want.some((w) => allPerms.includes(w))) pluginMisses.push(`${c} → needs ${want.join(' or ')}`);
}
rec('A6. every invoked PLUGIN command has an explicit allow-<command> grant',
  pluginMisses.length === 0,
  pluginMisses.length ? pluginMisses.join('; ') : list(invokedPlugin));

// The updater/process/dialog plugins are driven from Rust only (main.rs). Granting them a
// webview permission would hand a remote origin the ability to trigger installs, restarts
// and native dialogs — pure over-grant. Assert they stay off the capability.
const RUST_ONLY_PLUGINS = ['updater', 'process', 'dialog'];
const leaked = allPerms.filter((p) => RUST_ONLY_PLUGINS.some((pl) => p.startsWith(`${pl}:`)));
rec('A7. Rust-driven plugins (updater/process/dialog) get NO webview IPC permission',
  leaked.length === 0, leaked.length ? `over-granted: ${leaked.join(', ')}` : 'none granted');

// ── 7. The grant must cover the origin + window that actually load ───────────
// A permission listed in a capability that does not match the loaded origin is not a grant.
// Derive the origin from main.rs rather than hard-coding it.
const port = (mainrs.match(/const\s+PORT\s*:\s*u16\s*=\s*(\d+)/) || [])[1];
const label = (mainrs.match(/WebviewWindowBuilder::new\(\s*\w+\s*,\s*"([^"]+)"/) || [])[1];
const origin = port ? `http://127.0.0.1:${port}` : null;
const granting = caps.filter((c) => (c.permissions || []).some((p) => typeof p === 'string' && appPerms.has(p)));
// `platforms` is the third silent way a grant can be present but inert: tauri-build skips a
// capability whose platform list excludes the build target (tauri-build/src/acl.rs
// validate_capabilities), so `"platforms":["linux"]` would leave every command ACL-rejected
// on the only OS we ship. Absent = all platforms, which is what we want.
const shipsMac = (c) => !c.platforms || c.platforms.some((p) => String(p).toLowerCase() === 'macos');
const covers = granting.length > 0 && granting.every((c) => {
  const wins = c.windows || [];
  const urls = c.remote?.urls || [];
  return (wins.includes(label) || wins.includes('*'))
    && urls.some((u) => typeof u === 'string' && origin && u.startsWith(origin))
    && shipsMac(c);
});
rec('A8. the granting capability covers window + the REMOTE origin + the shipped platform',
  covers,
  granting.length === 0
    ? 'no capability grants any app command'
    : `window "${label}", origin ${origin}, platforms ${granting.map((c) => JSON.stringify(c.platforms ?? 'all')).join('/')} — capabilities: ${granting.map((c) => c.identifier).join(', ')}`);

console.log('\n' + '='.repeat(60));
console.log(fail
  ? 'VERDICT: NO-GO — a command the portal invokes is not permitted by the capability set (it will be ACL-rejected at runtime)'
  : 'VERDICT: GO — every app + plugin command the portal invokes is permitted for the loaded\n'
    + '            window/origin/platform, and every granted permission is backed by an invoked\n'
    + '            command or a registered exception.\n'
    + '            NOT PROVEN: (1) what the `core:default` permission SET expands to — this gate\n'
    + '            checks identifiers, not set contents; (2) that the updater downloads/verifies/\n'
    + '            installs — that needs a signed packaged build (operator).');
console.log('='.repeat(60));
process.exit(fail);
